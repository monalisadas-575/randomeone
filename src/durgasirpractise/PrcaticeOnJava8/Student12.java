package durgasirpractise.PrcaticeOnJava8;

 class Student12 {
  private String name;
  public int marks;

     public Student12(String name, int marks) {
         this.name = name;
         this.marks = marks;
     }

     public int getMarks() {
         return marks;
     }

     public void setMarks(int marks) {
         this.marks = marks;
     }

     public String getName() {
         return name;
     }

     public void setName(String name) {
         this.name = name;
     }
 }
